/**
 * Resolves the visual profile for any capability (including newly created capabilities in the Admin panel).
 */
export function getCapabilityVisualProfile(capability: Capability, parent?: Capability | null): CapabilityVisualProfile {
    const existing = CAPABILITY_PROFILES[capability.slug];
    if (existing) {
        if (capability.image) {
            return {
                ...existing,
                coverImage: capability.image,
                samples: existing.samples.map((sample, idx) =>
                    idx === 0 ? { ...sample, afterImage: capability.image! } : sample,
                ),
            };
        }
        return existing;
    }

    const parentSlug = parent?.slug ?? capability.parent?.slug ?? '2d';
    const parentProfile = CAPABILITY_PROFILES[parentSlug] ?? CAPABILITY_PROFILES['2d'];
    const heroImage = capability.image || parentProfile.coverImage;

    return {
        slug: capability.slug,
        coverImage: heroImage,
        turnaround: parentProfile.turnaround,
        formats: parentProfile.formats,
        samples: parentProfile.samples.map((sample, idx) =>
            idx === 0
                ? {
                      ...sample,
                      id: `${capability.slug}-sample-1`,
                      title: capability.title,
                      afterImage: heroImage,
                  }
                : sample,
        ),
    };
}

/**
 * Resolves the best display cover image for a capability card.
 */
export function getCapabilityCoverImage(capability: Capability, parent?: Capability | null): string {
    if (capability.image) {
        return capability.image;
    }
    return CAPABILITY_PROFILES[capability.slug]?.coverImage ?? getCapabilityVisualProfile(capability, parent).coverImage;
}
